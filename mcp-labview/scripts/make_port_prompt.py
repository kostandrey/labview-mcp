#!/usr/bin/env python3
"""make_port_prompt.py - assemble the LLM rewrite prompt for the
VI -> CompileToDFIRCPP -> dfir2cpp_cleaner -> clean-code pipeline.

Stage 4 of the conversion pipeline (recipe v3.53).  Takes the CLEANED
C++ produced by dfir2cpp_cleaner.py (plus optional lv_dfir.py JSON and
golden vectors captured live from the VI via arrread cycle) and emits a
complete, self-contained prompt for an LLM to produce the final clean
C++20 / Python port.

Usage:
  python make_port_prompt.py IN_clean.cpp [-o prompt.md]
      [--json IN.json]          # lv_dfir.py structured IR (labels/summary)
      [--golden vectors.json]   # [{"input": <str>, "expect": <hex>} , ...]
                                # or {"input": <hex-or-str>, "output": ...}
      [--lang cpp|py|both]      # requested target (default: cpp)
      [--vi NAME]               # source VI name for the header line

Deterministic: same inputs -> same prompt bytes.
"""
import argparse
import json
import os
import sys
import textwrap

TEMPLATE = """\
Below is code generated by the LabVIEW DFIR-to-C++ translator
(the LabVIEW compiler export via `Compile: Compile To DFIR CPP`,
normalized by the dfir2cpp-cleaner script).  It still contains NI
system primitives and translator placeholders: descriptors
(`_data[]` blobs, MakeValue/MakeTDR - already removed) and notation
for the recovered dataflow graph.

## Notation dictionary (do NOT invent other meanings!)

- `connect(&src, srcTerm, &dst, dstTerm, dfir_type("..."));` - a wire:
  output terminal `srcTerm` of node `src` is connected to input
  terminal `dstTerm` of node `dst`; the wire type is given in
  `dfir_type`.  `NULL` instead of `&node` = unconnected terminal.
- `dfir_type("U16 'label'")` - wire type + the element's label on the
  block diagram / front panel (label = name of the original
  control/constant).
- `Literal/*TYPE 'label'*/` - the value of a constant / control
  default, its type and label (e.g. `65535/*U16 'FFFF(U16)'*/`).
- `// uid=N (nameRef)` - the node's id in the original VI (keep these
  in comments for traceability).
- `CreateTunnel(..., Indexing|NonIndexing|Concatenate, ...)` -
  auto-indexing / plain / concatenating loop tunnel.
- `CreateShiftRegister(tdr, n)` + `GetRightShiftRegister()` - shift
  register: state carried across loop iterations.
- `CaseSelector` + `CreateRange(lo,hi)` + `SetDefaultDiagramIndex` -
  Case structure frames (selector ranges).
- Nested `{{ }}` - nested diagrams (loop body / Case frame).

## Task

1. Extract the pure mathematical/algorithmic essence without any
   dependency on the NI runtime (ignore translation artifacts:
   Create order, wires, duplicated terminals).
2. Explain the underlying algorithm step by step: data structures,
   key formulas, edge cases (empty input, overflow, indexing bounds,
   behavior of every Case frame).
3. Rewrite it as clean {lang_target}, eliminating the LabVIEW memory
   management boilerplate:
   - {lang_rules}
4. Verify yourself against the golden vectors at the end of this
   prompt (if given) and state the computed values next to the
   expected ones.

## Requirements on the result

- A single file; no NI headers (`extcode.h`, `fundtypes.h`, `lv_*.h`),
  no MgErr/Handles/NumericArrayResize.
- Deterministic behavior; no hidden mutable state.
- Derive function/variable names from the original VI labels; keep
  `uid=N` comments on key nodes.
- Explicitly list the edge cases and how you handled each.
- If the dump is insufficient for an unambiguous port - ask a question
  instead of guessing.

{golden_section}
"""

CODE_HEAD = "## Source code (normalized dump)\n\n```cpp\n"

CPP_RULES = """\
clean C++20 using `std::vector`, `std::span` and the standard
algorithms from `<algorithm>` / `<numeric>`; no raw pointers,
`new`/`delete` or manual memory management; range-for and algorithms
instead of hand-rolled loops where that reads better; `std::uint16_t`
et al. from `<cstdint>`; errors - via `std::expected`/exceptions, your
choice, but consistent"""

PY_RULES = """\
clean Python 3.10+ (type hints, `dataclasses`; structures as
`list`/`dict`/`bytes`; no third-party dependencies); prefer readable
named constants over hand-rolled bit-mask gymnastics"""

BOTH_RULES = CPP_RULES + ";\n   - and an equivalent in " + \
    PY_RULES[0].upper() + PY_RULES[1:]

LANG_RULES = {"cpp": CPP_RULES, "py": PY_RULES, "both": BOTH_RULES}
LANG_TARGET = {"cpp": "C++20",
               "py": "Python 3.10+",
               "both": "C++20 (primary) and Python 3.10+ (second listing)"}


def load_golden(path):
    """Accepts a JSON list of {"input": <str>, "expect": "<u16hex>"} or
    {"input": "...", "output": "<hexbytes>"} records (as captured by the
    arrread cycle golden runs)."""
    data = json.load(open(path, encoding='utf-8'))
    if isinstance(data, dict):
        data = [data]
    lines = ["## Golden vectors (captured live from the original VI)\n",
             "| input | expected result |", "|---|---|"]
    for rec in data:
        inp = rec.get("input", "")
        exp = rec.get("expect") or rec.get("output")
        if isinstance(exp, int):
            exp = "0x%04X" % exp
        lines.append("| `%s` | `%s` |" % (inp.replace('|', '\\|'), exp))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("input", help="cleaned .cpp from dfir2cpp_cleaner.py")
    ap.add_argument("-o", "--output")
    ap.add_argument("--json", help="lv_dfir.py structured IR (context)")
    ap.add_argument("--golden", help="JSON file with golden vectors")
    ap.add_argument("--lang", choices=["cpp", "py", "both"], default="cpp")
    ap.add_argument("--vi", default="", help="source VI name")
    args = ap.parse_args(argv)

    code = open(args.input, encoding='utf-8',
                errors='surrogateescape').read()
    header = ""
    if args.vi:
        header = "(source VI: %s)\n" % args.vi

    golden = ""
    if args.golden:
        golden = load_golden(args.golden)

    prompt = TEMPLATE.format(
        lang_target=LANG_TARGET[args.lang],
        lang_rules=textwrap.indent(LANG_RULES[args.lang], "   ").lstrip(),
        golden_section=golden) + CODE_HEAD + (header + code) + "\n```\n"

    out = prompt
    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print("wrote %s (%d chars)" % (args.output, len(out)))
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
